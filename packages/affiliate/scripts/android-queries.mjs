#!/usr/bin/env node
// Writes the Android 11+ <queries> block (package visibility) from the platform registry, so the manifest never drifts.
// Usage: node packages/affiliate/scripts/android-queries.mjs [path/to/AndroidManifest.xml]   (no path = print)
import { readFileSync, writeFileSync } from 'node:fs';
import { PLATFORMS } from '../dist/index.js';

const packages = new Set();
const schemes = new Set(['sms']);
const probe = { q: 'x', id: 'x', url: 'https://example.com', to: '+910000000000', text: 'x', lat: 0, lng: 0 };
for (const p of Object.values(PLATFORMS)) {
  if (p.android) packages.add(p.android);
  for (const fn of Object.values(p.scheme ?? {})) {
    let uri = null;
    try {
      uri = fn(probe);
    } catch {
      /* a scheme that needs other params still has its scheme in the source */
    }
    const m = (uri ?? String(fn)).match(/([a-z][a-z0-9+.-]*):\/\//);
    if (m && m[1] !== 'https' && m[1] !== 'http') schemes.add(m[1]);
  }
}

const pad = '        ';
const block = [
  '    <!-- akaya:queries:start (generated by packages/affiliate/scripts/android-queries.mjs; do not edit) -->',
  '    <queries>',
  ...[...packages].sort().map((p) => `${pad}<package android:name="${p}" />`),
  `${pad}<intent><action android:name="android.intent.action.VIEW" /><data android:scheme="https" /></intent>`,
  ...[...schemes]
    .sort()
    .map((s) => `${pad}<intent><action android:name="android.intent.action.VIEW" /><data android:scheme="${s}" /></intent>`),
  '    </queries>',
  '    <!-- akaya:queries:end -->',
].join('\n');

const file = process.argv[2];
if (!file) {
  console.log(block);
} else {
  const xml = readFileSync(file, 'utf8');
  const re = /    <!-- akaya:queries:start[\s\S]*?<!-- akaya:queries:end -->/;
  const next = re.test(xml) ? xml.replace(re, block) : xml.replace('</manifest>', `\n${block}\n</manifest>`);
  writeFileSync(file, next);
  console.log(`${file}: ${packages.size} packages, ${schemes.size} schemes`);
}
