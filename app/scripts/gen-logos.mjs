#!/usr/bin/env node
/**
 * Generates src/integrations/logos.generated.ts from permissively licensed icon sets, in order of preference:
 *   1. @iconify-json/logos (CC0-1.0, gilbarbara/logos): full-colour app marks
 *   2. @iconify-json/thesvg-color (MIT): full-colour app marks
 *   3. simple-icons (CC0-1.0): single-colour brand marks + official brand hex
 *   4. @iconify-json/cib (CC0-1.0), @iconify-json/mdi (Apache-2.0): single-colour fallbacks
 * Only icons used by the catalog are emitted. Apps with no match fall back to the monogram tile.
 * Run: node scripts/gen-logos.mjs
 */
import fs from 'node:fs';
import path from 'node:path';
import { createRequire } from 'node:module';
import * as si from 'simple-icons';

const require = createRequire(import.meta.url);
const root = path.dirname(path.dirname(new URL(import.meta.url).pathname));
/** Iconify JSON sets used, all permissive: CC0 (logos, cib), MIT (thesvg, vscode-icons), Apache-2.0 (mdi). */
const SETS = Object.fromEntries(
  ['logos', 'thesvg-color', 'thesvg', 'cib', 'vscode-icons', 'mdi'].map((s) => [
    s,
    require(`@iconify-json/${s}/icons.json`),
  ]),
);
const LICENSE = {
  logos: 'CC0-1.0',
  'thesvg-color': 'MIT',
  thesvg: 'MIT',
  cib: 'CC0-1.0',
  'vscode-icons': 'MIT',
  mdi: 'Apache-2.0',
};
const MONO = new Set(['thesvg', 'cib', 'mdi']);

// catalog ids (parsed from source so the script needs no TS toolchain)
const catalogSrc = fs.readFileSync(path.join(root, 'src/integrations/catalog.ts'), 'utf8');
const ids = [...catalogSrc.matchAll(/^\s*\[\s*'([a-z0-9-]+)',\s*'/gm)].map((m) => m[1]);

/** explicit picks: `logos:<name>` or `si:<slug>`; `none` = deliberately keep the monogram */
const OVERRIDES = JSON.parse(fs.readFileSync(path.join(root, 'scripts/logo-map.json'), 'utf8'));

const siBySlug = new Map(
  Object.values(si)
    .filter((x) => x && x.slug)
    .map((x) => [x.slug, x]),
);
const MAX_BYTES = 12000; // keep the bundle lean; heavier full-colour marks fall back to Simple Icons

function fromIconify(set, name, maxAspect = 1.7) {
  const data = SETS[set];
  let ic = data.icons[name];
  if (!ic && data.aliases?.[name]) ic = { ...data.icons[data.aliases[name].parent], ...data.aliases[name] };
  if (!ic || !ic.body) return null;
  if (ic.body.length > MAX_BYTES) return null;
  const w = ic.width ?? data.width ?? 16;
  const h = ic.height ?? data.height ?? 16;
  // wordmarks (very wide) read poorly on a square tile
  if (w / h > maxAspect) return null;
  return {
    src: set,
    license: LICENSE[set],
    name,
    vb: `${ic.left ?? 0} ${ic.top ?? 0} ${w} ${h}`,
    body: ic.body,
    ...(MONO.has(set) ? { mono: true } : {}),
  };
}
function fromSi(slug) {
  const ic = siBySlug.get(slug);
  if (!ic) return null;
  return {
    src: 'simple-icons',
    license: 'CC0-1.0',
    name: ic.slug,
    vb: '0 0 24 24',
    body: `<path d="${ic.path}"/>`,
    hex: `#${ic.hex}`,
    mono: true,
  };
}
function pick(id) {
  const o = OVERRIDES[id];
  const tries = [];
  // explicit picks may be compact wordmarks (e.g. Zoho); auto picks must be near-square marks
  const explicit = new Set(o ? [].concat(o) : []);
  for (const t of explicit) tries.push(t);
  const bare = id.replace(/-/g, '');
  tries.push(
    `logos:${id}-icon`,
    `logos:${id}`,
    `thesvg-color:${id}`,
    `thesvg-color:${bare}`,
    `si:${bare}`,
    `si:${id}`,
    `cib:${id}`,
  );
  for (const t of tries) {
    if (t === 'none') return null;
    const [kind, name] = t.split(':');
    const r = kind === 'si' ? fromSi(name) : fromIconify(kind, name, explicit.has(t) ? 3.2 : 1.7);
    if (r) return r;
  }
  return null;
}

const out = {};
const missing = [];
const stats = {};
for (const id of ids) {
  const r = pick(id);
  if (r) {
    out[id] = r;
    stats[r.src] = (stats[r.src] ?? 0) + 1;
  } else missing.push(id);
}

const header = `/* AUTO-GENERATED by scripts/gen-logos.mjs. Do not edit by hand.
 * Sources: simple-icons (CC0), @iconify-json/logos (CC0), @iconify-json/cib (CC0), @iconify-json/thesvg(-color) (MIT),
 * @iconify-json/vscode-icons (MIT), @iconify-json/mdi (Apache-2.0). Per-logo source is in each entry.
 * Logos are trademarks of their owners; shown only to identify the integration. See README "Brand logos". */
import type { BrandLogo } from './logo-types';

`;
fs.writeFileSync(
  path.join(root, 'src/integrations/logos.generated.ts'),
  header +
    `export const LOGOS: Record<string, BrandLogo> = ${JSON.stringify(out)};\n\n` +
    `/** catalog ids that show the monogram fallback tile */\nexport const LOGO_FALLBACKS: string[] = ${JSON.stringify(missing)};\n`,
);
fs.writeFileSync(
  path.join(root, 'scripts/logo-report.json'),
  JSON.stringify(
    {
      total: ids.length,
      ...stats,
      fallback: missing.length,
      missing,
      picks: Object.fromEntries(Object.entries(out).map(([k, v]) => [k, `${v.src}:${v.name}`])),
    },
    null,
    2,
  ),
);
console.log(`apps ${ids.length}`, stats, `fallback ${missing.length}`);
console.log('missing:', missing.join(', '));
